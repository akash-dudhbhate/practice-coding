// Lesson 18 — Easy P02: push, pop, shift, unshift
let fruits = ["apple", "banana", "cherry"];
fruits.push("date");      console.log(fruits); // ["apple","banana","cherry","date"]
fruits.pop();             console.log(fruits); // ["apple","banana","cherry"]
fruits.unshift("avocado"); console.log(fruits); // ["avocado","apple","banana","cherry"]
fruits.shift();           console.log(fruits); // ["apple","banana","cherry"]
